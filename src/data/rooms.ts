import { Room, Entity } from '../types/game';
import { SKILLS_DATABASE } from './skills';

// Helper to create enemy entities
export function createEnemy(
  id: string,
  name: string,
  x: number,
  y: number,
  hp: number,
  ac: number,
  speed: number,
  attackSkillId: string,
  color: string,
  icon: string
): Entity {
  const skill = SKILLS_DATABASE[attackSkillId] || SKILLS_DATABASE['melee_strike'];
  return {
    id,
    name,
    isPlayer: false,
    x,
    y,
    hp,
    maxHp: hp,
    ac,
    speed,
    remainingSpeed: speed,
    attributes: { STR: 14, DEX: 12, CON: 12, INT: 8, WIS: 10, CHA: 6 },
    conditions: [],
    skills: [skill],
    color,
    icon,
    deathSaves: { successes: 0, failures: 0, stabilized: false, dead: false },
    hasUsedAction: false,
    hasUsedBonusAction: false,
  };
}

